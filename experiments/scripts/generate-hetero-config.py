#!/usr/bin/env python3
"""
Generate CL2 testoverrides for heterogeneous-capacity (HC-V) scenarios.

Emits a YAML file consumable by `clusterloader --testoverrides=<file>` that
pins each of the 10 KWOK shards to a specific CPU / Memory capacity according
to the requested capacity-variance level V.

Design constraints (see experiments/experiment-design.md §6.2):
  - pod_size = 24 CPU / 192 Gi (HC-1 baseline, unchanged)
  - Each node must hold exactly 1 pod  =>  24 <= CPU < 48 per shard
  - Total CPU across 10 shards == 320  =>  cluster pod-capacity == N (same as HC-1)
  - Memory scales proportionally to CPU at 8 Gi per CPU (same as 32 CPU / 256 Gi)

Supported V levels: 0, 0.3, 0.6, 1.0 (discrete table, not interpolated).

Usage:
  generate-hetero-config.py --variance 0.6 --out /tmp/overrides.yaml
  generate-hetero-config.py --variance 1.0              # prints to stdout
  generate-hetero-config.py --list                       # dump all V levels
"""

import argparse
import sys
from pathlib import Path


# --------------------------------------------------------------------------
# Shard CPU tables. Each row has exactly 10 entries (one per shard s0..s9),
# all values in [24, 47], and sums to 320. Memory is derived as CPU * 8 Gi.
#
# The distributions approximate a discretized lognormal(mean=log(32), sigma=V)
# clamped to [24, 47] but hand-tuned to keep exact sum=320 and simple integer
# CPU values.
#
# Score spread (LeastAllocated, pod=24 CPU):
#   score(node) = (CPU - 24) / CPU * 100
#   V=0    : all 25
#   V=0.3  : 40 CPU -> 40,  28 CPU -> 14
#   V=0.6  : 44 CPU -> 45,  24 CPU -> 0
#   V=1.0  : 45 CPU -> 47,  24 CPU -> 0
# --------------------------------------------------------------------------
SHARD_CPU_TABLES: dict[str, list[int]] = {
    "0":   [32, 32, 32, 32, 32, 32, 32, 32, 32, 32],   # sum 320, flat (HC-1)
    "0.3": [40, 36, 34, 32, 32, 32, 30, 28, 28, 28],   # sum 320
    "0.6": [44, 40, 36, 32, 32, 30, 28, 28, 26, 24],   # sum 320
    "1.0": [45, 43, 40, 34, 32, 28, 26, 24, 24, 24],   # sum 320
}

POD_CPU = 24      # HC-1 pod request in CPU units
POD_MEM_GI = 192  # HC-1 pod request in Gi (kept for symmetry; not emitted)
MEM_PER_CPU_GI = 8  # 32 CPU / 256 Gi == 8 Gi per CPU


def validate_table(name: str, row: list[int]) -> None:
    """Fail fast on any table that violates the HC-V constraints."""
    if len(row) != 10:
        raise ValueError(f"V={name}: need 10 shards, got {len(row)}")
    for cpu in row:
        if cpu < POD_CPU:
            raise ValueError(f"V={name}: CPU={cpu} < pod_size={POD_CPU} (node can't fit pod)")
        if cpu >= 2 * POD_CPU:
            raise ValueError(f"V={name}: CPU={cpu} >= 2*pod_size={2*POD_CPU} (node holds >1 pod)")
    total = sum(row)
    expected = 32 * 10  # 320
    if total != expected:
        raise ValueError(f"V={name}: sum(CPU)={total}, expected {expected}")


def score_spread(row: list[int]) -> tuple[float, float]:
    """LeastAllocated score range for a 24-CPU pod landing on an empty node."""
    scores = [(c - POD_CPU) / c * 100 for c in row]
    return min(scores), max(scores)


def format_overrides(variance: str) -> str:
    """Build the CL2 testoverrides YAML body for a given V level."""
    if variance not in SHARD_CPU_TABLES:
        raise KeyError(f"unknown variance '{variance}'; supported: {sorted(SHARD_CPU_TABLES)}")
    row = SHARD_CPU_TABLES[variance]
    validate_table(variance, row)

    lo, hi = score_spread(row)
    lines = [
        f"# Auto-generated by generate-hetero-config.py  (variance V={variance})",
        f"# Shard CPU capacities: {row}",
        f"# Sum CPU = {sum(row)}  (==320, cluster pod-capacity = N)",
        f"# Max/min CPU ratio = {max(row)/min(row):.2f}x",
        f"# LeastAllocated score spread (pod=24 CPU): [{lo:.1f}, {hi:.1f}]",
        f'CAPACITY_VARIANCE: "{variance}"',
    ]
    for i, cpu in enumerate(row):
        mem_gi = cpu * MEM_PER_CPU_GI
        lines.append(f'CPU_S{i}: "{cpu}"')
        lines.append(f'MEM_S{i}: "{mem_gi}Gi"')
    return "\n".join(lines) + "\n"


def list_all() -> str:
    """Dump a summary of every V level for quick inspection."""
    rows = []
    rows.append(f"{'V':<6} {'CPU per shard':<52} {'sum':<5} {'max/min':<8} {'score range':<16}")
    rows.append("-" * 100)
    for v in sorted(SHARD_CPU_TABLES, key=float):
        row = SHARD_CPU_TABLES[v]
        validate_table(v, row)
        lo, hi = score_spread(row)
        cpus = " ".join(f"{c:>2}" for c in row)
        rows.append(f"{v:<6} [{cpus}]  {sum(row):<5} {max(row)/min(row):<8.2f} [{lo:>5.1f}, {hi:>5.1f}]")
    return "\n".join(rows) + "\n"


def main() -> int:
    p = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    p.add_argument("--variance", "-v", help="Variance level; one of: " + ", ".join(sorted(SHARD_CPU_TABLES, key=float)))
    p.add_argument("--out", "-o", help="Output file path; stdout if omitted")
    p.add_argument("--list", action="store_true", help="Print summary of all V levels and exit")
    args = p.parse_args()

    if args.list:
        sys.stdout.write(list_all())
        return 0

    if args.variance is None:
        p.error("--variance is required (or pass --list)")

    try:
        body = format_overrides(args.variance)
    except (KeyError, ValueError) as e:
        print(f"error: {e}", file=sys.stderr)
        return 1

    if args.out:
        Path(args.out).write_text(body, encoding="utf-8")
    else:
        sys.stdout.write(body)
    return 0


if __name__ == "__main__":
    sys.exit(main())
